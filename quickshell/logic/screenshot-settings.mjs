export const screenshotDefaults = {
  schemaVersion: 1, directory: '', autoSave: false, color: '#ff5252', strokeWidth: 4, fontSize: 24,
  localKeys: { select: 'V', brush: 'B', line: 'L', arrow: 'A', rectangle: 'R', ellipse: 'O',
    text: 'T', highlight: 'H', redact: 'X', crop: 'C', undo: 'Ctrl+Z', redo: 'Ctrl+Shift+Z',
    copy: 'Ctrl+C', save: 'Ctrl+S', accept: 'Return', cancel: 'Escape', delete: 'Delete' },
  globalKeys: { edit: 'Super+Shift+S', copy: 'Super+Ctrl+S', window: 'Alt+Print', monitor: 'Print' },
};

const isObject = value => value && typeof value === 'object' && !Array.isArray(value);
const modifiers = ['Super', 'Ctrl', 'Alt', 'Shift'];
const aliases = { control: 'Ctrl', ctrl: 'Ctrl', meta: 'Super', super: 'Super', alt: 'Alt', shift: 'Shift' };
const names = { enter: 'Return', return: 'Return', esc: 'Escape', escape: 'Escape', delete: 'Delete',
  backspace: 'Backspace', print: 'Print', space: 'Space', tab: 'Tab', home: 'Home', end: 'End',
  pageup: 'PageUp', pagedown: 'PageDown', left: 'Left', right: 'Right', up: 'Up', down: 'Down' };

export function normalizeShortcut(input) {
  if (typeof input !== 'string' || input.length > 80) throw new Error('Invalid shortcut');
  if (!input.trim()) return '';
  const parts = input.split('+').map(part => part.trim());
  const rawKey = parts.pop();
  const key = names[rawKey.toLowerCase()] || (/^[a-z0-9]$/i.test(rawKey) ? rawKey.toUpperCase()
    : /^F([1-9]|[12][0-9]|3[0-5])$/i.test(rawKey) ? rawKey.toUpperCase() : '');
  const mods = parts.map(part => aliases[part.toLowerCase()]);
  if (!key || mods.some(mod => !mod) || new Set(mods).size !== mods.length) throw new Error('Invalid shortcut: ' + input);
  return modifiers.filter(mod => mods.includes(mod)).concat([key]).join('+');
}

export function matchesScreenshotShortcut(key, flags, shortcut) {
  if (!shortcut) return false;
  const special = { 0x01000000: 'Escape', 0x01000001: 'Tab', 0x01000002: 'Tab',
    0x01000003: 'Backspace', 0x01000004: 'Return', 0x01000005: 'Return',
    0x01000007: 'Delete', 0x01000009: 'Print', 0x01000010: 'Home', 0x01000011: 'End',
    0x01000012: 'Left', 0x01000013: 'Up', 0x01000014: 'Right', 0x01000015: 'Down',
    0x01000016: 'PageUp', 0x01000017: 'PageDown', 32: 'Space' };
  const name = special[key] || (key >= 0x01000030 && key <= 0x01000052 ? 'F' + (key - 0x01000030 + 1)
    : (key >= 48 && key <= 57) || (key >= 65 && key <= 90) ? String.fromCharCode(key) : '');
  if (!name) return false;
  const bits = { Super: 0x10000000, Ctrl: 0x04000000, Alt: 0x08000000, Shift: 0x02000000 };
  return modifiers.filter(mod => flags & bits[mod]).concat([name]).join('+') === normalizeShortcut(shortcut);
}

export function parseScreenshotSettings(input) {
  if (!isObject(input)) throw new Error('Screenshot settings must be an object');
  const value = Object.assign({}, screenshotDefaults, input);
  if (value.schemaVersion !== 1 || typeof value.autoSave !== 'boolean'
    || typeof value.directory !== 'string' || value.directory.length > 4096 || /[\x00-\x1f]/.test(value.directory)
    || (value.directory !== '' && !value.directory.startsWith('/'))
    || !/^#[\da-f]{6}$/i.test(value.color)
    || !Number.isFinite(value.strokeWidth) || value.strokeWidth < 1 || value.strokeWidth > 100
    || !Number.isFinite(value.fontSize) || value.fontSize < 8 || value.fontSize > 200)
    throw new Error('Invalid screenshot settings');
  for (const group of ['localKeys', 'globalKeys']) {
    if (input[group] !== undefined && !isObject(input[group])) throw new Error('Invalid shortcut group');
    value[group] = Object.assign({}, screenshotDefaults[group]);
    const seen = new Set();
    for (const action of Object.keys(value[group])) {
      const key = normalizeShortcut(input[group]?.[action] ?? value[group][action]);
      if (key && seen.has(key)) throw new Error('Duplicate shortcut: ' + key);
      if (key) seen.add(key);
      value[group][action] = key;
    }
  }
  return value;
}

function bindingSpellings(parts, key) {
  function permutations(items) {
    if (!items.length) return [[]];
    const result = [];
    items.forEach(function(item, index) {
      permutations(items.filter(function(_, i) { return i !== index; })).forEach(function(rest) {
        result.push([item].concat(rest));
      });
    });
    return result;
  }
  const canonical = parts.concat([key]).join(' + ');
  const spellings = [];
  permutations(parts).forEach(function(order) {
    ['+', ' + '].forEach(function(separator) {
      const spelling = order.concat([key]).join(separator);
      if (spelling !== canonical && spellings.indexOf(spelling) < 0) spellings.push(spelling);
    });
  });
  spellings.push(canonical);
  return spellings;
}

export function hyprlandScreenshotBindings(settings) {
  const value = parseScreenshotSettings(settings);
  const lines = ['-- Generated by Pentad. Source this fragment from your Hyprland Lua config.',
    '-- The configured combinations replace their previous bindings when sourced.'];
  for (const action of Object.keys(value.globalKeys)) {
    const shortcut = value.globalKeys[action];
    if (!shortcut) continue;
    const parts = shortcut.split('+');
    const key = parts.pop();
    const spellings = bindingSpellings(parts.map(mod => mod.toUpperCase()), key);
    const binding = spellings[spellings.length - 1];
    spellings.forEach(function(spelling) {
      lines.push('hl.unbind(' + JSON.stringify(spelling) + ')');
    });
    lines.push('hl.bind(' + JSON.stringify(binding) + ', hl.dsp.global("pentad:screenshot-' + action + '"))');
  }
  return lines.join('\n') + '\n';
}
